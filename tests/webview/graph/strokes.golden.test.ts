describe.each(["rounded", "angular"] as const)("fixture history strokes (%s)", (style) => {
  it.each(Object.keys(expected) as Array<keyof typeof histories>)("draws %s exactly", (name) => {
    const commits = histories[name];
    const layout = computeGraphLayout(commits, null);
    const drawings = expected[name][style];

    const panels = drawings.flatMap(([rows]) => rows);
    expect(panels).toHaveLength(commits.length + 1);
    expect(new Set(panels)).toEqual(new Set([null, ...commits.keys()]));

    for (const [rows, paths] of drawings) {
      expect(paths).toHaveLength(layout.branches.length);
      for (const row of rows) {
        const expansion = row === null ? null : { row, height: 250 };
        const drawn = layout.branches.map((branch) =>
          branchStrokes(branch, style === "angular", expansion)
        );
        // Nothing in these histories changes relation or committed state, so
        // each branch is a single stroke in its own colour.
        const wanted = layout.branches.map((branch, index) => [
          { path: paths[index], colour: branch.colour, isCommitted: true, relation: "normal" }
        ]);
        expect(drawn, `details under row ${String(row)}`).toEqual(wanted);
      }
    }
  });
});
